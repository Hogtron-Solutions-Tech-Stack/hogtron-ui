def background(rgb: np.ndarray) -> np.ndarray:
    k = 24
    corners = np.concatenate([rgb[:k, :k].reshape(-1, 3), rgb[:k, -k:].reshape(-1, 3), rgb[-k:, :k].reshape(-1, 3),
                              rgb[-k:, -k:].reshape(-1, 3)])
    return np.median(corners, axis=0)


def mask_of(rgb: np.ndarray, bg: np.ndarray, thresh: float = 38.0) -> np.ndarray:
    return np.sqrt(((rgb - bg[None, None, :]) ** 2).sum(axis=2)) > thresh


def components(mask: np.ndarray, want: int):
    """The `want` largest blobs (after closing small gaps), as (y0, y1, x0, x1), in reading order."""
    closed = ndimage.binary_closing(mask, iterations=6)
    filled = ndimage.binary_fill_holes(closed)
    lab, n = ndimage.label(filled)
    boxes = ndimage.find_objects(lab)
    sizes = ndimage.sum(filled, lab, range(1, n + 1))
    order = np.argsort(sizes)[::-1][:want]
    picked = [boxes[i] for i in order]
    out = [(b[0].start, b[0].stop, b[1].start, b[1].stop) for b in picked]
    if len(out) < want:
        raise SystemExit(f"found {len(out)} shapes, wanted {want}")
    # reading order: rows by centre y (three bands), then x
    cy = np.array([(b[0] + b[1]) / 2 for b in out])
    h = mask.shape[0]
    rows = np.floor(cy / (h / 3)).astype(int)
    return [b for _, _, b in sorted(zip(rows, [(bb[2] + bb[3]) / 2 for bb in out], out))]


def cut(rgb, mask, box, size, pad_frac, square=True):
    y0, y1, x0, x1 = box
    if square:
        cy, cx = (y0 + y1) / 2, (x0 + x1) / 2
        half = max(y1 - y0, x1 - x0) / 2 * (1 + pad_frac)
        y0, y1, x0, x1 = int(cy - half), int(cy + half), int(cx - half), int(cx + half)
        y0, x0 = max(0, y0), max(0, x0)
    crop = rgb[y0:y1, x0:x1]
    a = ndimage.binary_fill_holes(mask[y0:y1, x0:x1]).astype(np.float32)
    a = ndimage.gaussian_filter(a, 1.2)
    img = Image.fromarray(np.dstack([crop, np.clip(a, 0, 1) * 255]).astype(np.uint8), "RGBA")
    return img.resize((size, size), Image.LANCZOS)


def do_sheets(table, size, pad, suffix, dry):
    for sheet, names in table.items():
        path = RAW / f"{sheet}.png"
        if not path.exists():
            print(f"skip {sheet}: no raw yet")
            continue
        rgb = np.asarray(Image.open(path).convert("RGB")).astype(np.float32)
        bg = background(rgb)
        m = mask_of(rgb, bg)
        boxes = components(m, len(names))
        for name, box in zip(names, boxes):
            img = cut(rgb.astype(np.uint8), m, box, size, pad)
            dest = MEDIA / f"{name}{suffix}.tga"
            print(("would write " if dry else "wrote ") + f"{dest.name} {img.size} from {sheet} box {box} (bg {bg.astype(int).tolist()})")
            if not dry:
                img.save(dest, format="TGA", rle=False)


def save(img, name, dry):
    dest = MEDIA / f"{name}.tga"
    print(("would write " if dry else "wrote ") + f"{dest.name} {img.size}")
    if not dry:
        img.save(dest, format="TGA", rle=False)


def tileable(img: Image.Image, frac: float = 0.18) -> Image.Image:
    """Crossfade opposite edges so the texture repeats without a seam (both directions)."""
    a = np.asarray(img.convert("RGB")).astype(np.float32)
    for axis in (1, 0):
        n = a.shape[axis]
        k = int(n * frac)
        t = np.linspace(0, 1, k)
        if axis == 1:
            head, tail = a[:, :k], a[:, n - k:]
            a = a[:, : n - k].copy()
            a[:, :k] = tail * (1 - t)[None, :, None] + head * t[None, :, None]
        else:
            head, tail = a[:k], a[n - k:]
            a = a[: n - k].copy()
            a[:k] = tail * (1 - t)[:, None, None] + head * t[:, None, None]
    return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8))


def bbox(rgb, thresh=38.0, fill=True):
    bg = background(rgb)
    m = mask_of(rgb, bg, thresh)
    m = ndimage.binary_opening(m, iterations=2)
    if fill:   # a plaque's slate face ~ the background: keep it (never for the frame: its inside must stay open)
        m = ndimage.binary_fill_holes(ndimage.binary_closing(m, iterations=8))
    ys, xs = np.where(m)
    return ys.min(), ys.max() + 1, xs.min(), xs.max() + 1, m


def do_menu(dry):
    # background tile: dark slate, seamless, 256 px
    bg = Image.open(RAW / "menu_bg.png").convert("RGB")
    save(tileable(bg).resize((256, 256), Image.LANCZOS).convert("RGBA"), "menu_bg", dry)
    # frame: corner (top-left, 128 px) + a horizontal and a vertical edge strip from the plain run between the corner
    # filigree and the mid-edge clasp. Alpha = the frame's own mask (inside / outside are black and cut away).
    fr = np.asarray(Image.open(RAW / "menu_frame.png").convert("RGB")).astype(np.float32)
    y0, y1, x0, x1, m = bbox(fr, 30.0, fill=False)
    rgba = np.dstack([fr, ndimage.gaussian_filter(m.astype(np.float32), 1.0) * 255]).astype(np.uint8)
    full = Image.fromarray(rgba[y0:y1, x0:x1], "RGBA")
    W, H = full.size
    c = int(W * 0.14)                                    # corner box: frame + filigree
    save(full.crop((0, 0, c, c)).resize((128, 128), Image.LANCZOS), "menu_corner", dry)
    run0, run1 = int(W * 0.20), int(W * 0.40)            # between the corner filigree and the clasp at the middle
    thick = int(H * 0.05)
    save(full.crop((run0, 0, run1, thick)).resize((256, 32), Image.LANCZOS), "menu_edge_h", dry)
    save(full.crop((0, run0, thick, run1)).resize((32, 256), Image.LANCZOS), "menu_edge_v", dry)
    # header: the plaque, cropped to itself, 1024 x 128
    hd = np.asarray(Image.open(RAW / "menu_header.png").convert("RGB")).astype(np.float32)
    y0, y1, x0, x1, m = bbox(hd, 30.0)
    rgba = np.dstack([hd, ndimage.gaussian_filter(m.astype(np.float32), 1.0) * 255]).astype(np.uint8)
    save(Image.fromarray(rgba[y0:y1, x0:x1], "RGBA").resize((1024, 128), Image.LANCZOS), "menu_header", dry)
    # sidebar strip: crop to the strip, 128 x 512
    sd = np.asarray(Image.open(RAW / "menu_side.png").convert("RGB")).astype(np.float32)
    y0, y1, x0, x1, m = bbox(sd, 18.0)
    save(Image.fromarray(sd[y0:y1, x0:x1].astype(np.uint8)).resize((128, 512), Image.LANCZOS).convert("RGBA"), "menu_side", dry)


def band_strip(raw: Path, blend: float = 0.12, floor: int = 10) -> Image.Image:
    """An energy band on black -> a 512x64 strip that loops left to right (same cut as process_cast_art.py)."""
    im = np.asarray(Image.open(raw).convert("RGB")).astype(np.float32)
    lum = im.mean(axis=2)
    rows = lum.mean(axis=1)
    lit = np.where(rows > max(6.0, rows.max() * 0.15))[0]
    c = int(round((lit * rows[lit]).sum() / rows[lit].sum())) if len(lit) else lum.shape[0] // 2
    h, w = lum.shape
    ch = int(round(w / 8))
    top = max(0, min(h - ch, c - ch // 2))
    crop = im[top: top + ch]
    k = int(round(crop.shape[1] * blend))
    t = np.linspace(0, 1, k)[None, :, None]
    out = crop[:, : crop.shape[1] - k].copy()
    out[:, :k] = crop[:, crop.shape[1] - k:] * (1 - t) + crop[:, :k] * t
    strip = np.asarray(Image.fromarray(np.clip(out, 0, 255).astype(np.uint8)).resize((512, 64), Image.LANCZOS)).astype(np.float32)
    strip = np.where(strip.max(axis=2, keepdims=True) < floor, 0, strip)
    return Image.fromarray(np.dstack([strip, np.full(strip.shape[:2], 255.0)]).astype(np.uint8), "RGBA")


def do_bars(dry):
    save(band_strip(RAW / "xp_fill.png"), "xp_fill", dry)
    save(band_strip(RAW / "xp_rested.png"), "xp_rested", dry)
    pl = np.asarray(Image.open(RAW / "info_plate.png").convert("RGB")).astype(np.float32)
    y0, y1, x0, x1, m = bbox(pl, 30.0, fill=True)
    rgba = np.dstack([pl, ndimage.gaussian_filter(m.astype(np.float32), 1.0) * 255]).astype(np.uint8)
    save(Image.fromarray(rgba[y0:y1, x0:x1], "RGBA").resize((1024, 128), Image.LANCZOS), "info_plate", dry)


