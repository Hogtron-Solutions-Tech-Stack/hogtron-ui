"""Packager configs for the per-module CurseForge projects (dev/split/projects.json -> dev/split/pkgmeta/*.pkgmeta).

Sean 2026-10-18: "have them install the Hogtron UI, but some of the other ones underneath it can be individual
installs ... you can look them up on Curse Forge as well". Each project packages ONLY its own folder(s); a module
declares the core project as a required dependency (CurseForge installs it with the module) once the core's slug is
known. The all-in-one zip keeps using the repo-root .pkgmeta.

    python dev/split/make_pkgmeta.py --write     # regenerate the configs (tests fail when they are stale)
    python dev/split/make_pkgmeta.py --matrix    # the GitHub Actions matrix (one JSON line)
    python dev/split/make_pkgmeta.py --check     # exit 1 when a generated file differs from what it would write
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = ROOT / "dev" / "split"
OUT = HERE / "pkgmeta"
REPO_ONLY = ["tests", "docs", "dev", "dist", ".github", ".gitattributes", "requirements-dev.txt", "README.md", "CLAUDE.md"]


def load() -> dict:
    return json.loads((HERE / "projects.json").read_text(encoding="utf-8"))


def addon_folders() -> list[str]:
    return sorted(p.name for pat in ("HogHeals*", "HogTron*") for p in ROOT.glob(pat) if p.is_dir())


def root_ignores() -> list[str]:
    """The repo .pkgmeta's own ignore patterns that live inside an addon folder (e.g. Awards' source art)."""
    out, on = [], False
    for line in (ROOT / ".pkgmeta").read_text(encoding="utf-8").splitlines():
        if line.startswith("ignore:"):
            on = True
            continue
        if on:
            if line.startswith("  - "):
                out.append(line[4:].strip())
            elif line.strip() and not line.startswith(" "):
                on = False
    return [p for p in out if "/" in p]


def projects(cfg: dict) -> list[dict]:
    core = cfg["core"]
    out = [{"name": core["name"], "title": core["title"], "folders": core["folders"], "curse_id": core.get("curse_id", ""),
            "requires": []}]
    for m in cfg["modules"]:
        req = [core["slug"]] if core.get("slug") else []
        out.append({"name": m["name"], "title": m["title"], "folders": [m["name"]], "curse_id": m.get("curse_id", ""), "requires": req})
    return out


def pkgmeta(p: dict, every: list[str], extra_ignores: list[str]) -> str:
    own = p["folders"]
    lines = [
        f"# GENERATED by dev/split/make_pkgmeta.py from dev/split/projects.json - edit those, then --write.",
        f"# CurseForge project: {p['title']} ({p['curse_id'] or 'not created yet'})",
        f"package-as: {p['name']}",
        "",
        "manual-changelog:",
        "  filename: CHANGELOG.md",
        "  markup-type: markdown",
        "",
        "move-folders:",
    ]
    # the package's own folder moves into the package dir itself, so it goes LAST (as in the repo .pkgmeta)
    for f in sorted(own, key=lambda f: f == p["name"]):
        lines.append(f"  {p['name']}/{f}: {f}")
    lines += ["", "ignore:"]
    for item in REPO_ONLY + [f for f in every if f not in own]:
        lines.append(f"  - {item}")
    for pat in extra_ignores:
        if pat.split("/", 1)[0] in own:
            lines.append(f"  - {pat}")
    if p["requires"]:
        lines += ["", "required-dependencies:"] + [f"  - {s}" for s in p["requires"]]
    return "\n".join(lines) + "\n"


def build() -> dict[str, str]:
    cfg = load()
    every, extra = addon_folders(), root_ignores()
    return {f"{p['name']}.pkgmeta": pkgmeta(p, every, extra) for p in projects(cfg)}


def matrix() -> str:
    """curse_id is handed to the upload step only while projects.json says live: true (see its _readme)."""
    cfg = load()
    live = cfg.get("live") is True
    rows = [{"name": p["name"], "folders": ",".join(p["folders"]), "curse_id": p["curse_id"] if live else ""} for p in projects(cfg)]
    return json.dumps(rows, separators=(",", ":"))


def main(argv: list[str]) -> int:
    if "--matrix" in argv:
        print(matrix())
        return 0
    files = build()
    if "--write" in argv:
        OUT.mkdir(parents=True, exist_ok=True)
        for old in OUT.glob("*.pkgmeta"):
            if old.name not in files:
                old.unlink()
        for name, text in files.items():
            (OUT / name).write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {len(files)} configs to {OUT.relative_to(ROOT)}")
        return 0
    stale = [n for n, t in files.items() if not (OUT / n).is_file() or (OUT / n).read_text(encoding="utf-8") != t]
    if stale:
        print("stale:", ", ".join(stale), "- run python dev/split/make_pkgmeta.py --write")
        return 1
    print(f"{len(files)} configs up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
