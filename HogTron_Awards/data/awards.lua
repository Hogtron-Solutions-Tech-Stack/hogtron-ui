-- HogTron Awards: the 75 awards. 38 honors, 37 roasts. Pure data; Metrics.lua says how each metric is measured.
--
-- Fields
--   id, name, kind ("honor" | "roast"), flavor (one line)
--   metric   key into HogTronAwards.Metrics.DEFS
--   dir      "high" (most wins) | "low" (least wins)
--   ctx      "any" or a list of "dungeon" | "raid" | "bg"
--   role     optional: "tank" | "healer" | "dps" | "nontank" (roles come from the group tool, else from the meter)
--   min      optional qualifying value (default 1 for "high"; "low" awards need the player to have taken part)
--   emote    key into HogTronAwards.EMOTES (animation the 3D model plays)
--   icon     image prompt SUBJECT; the full prompt is PROMPT_TEMPLATE with {subject} filled in (dev/gen_award_icons.py)
--   headline optional priority for the centre spot (lower = preferred)
--   note     why an award was reframed for WoW: Forever (combat numbers are hidden from addons; see Metrics.lua)
--
-- WoW: Forever rule behind every metric: addons get NO combat log and every amount from the game's damage meter
-- (C_DamageMeter) is a SECRET value - showable, not comparable. What IS usable: the meter's player ORDER (Blizzard
-- ranks the list itself) and plain numbers each client knows about its own player. So "who did the most" comes from
-- meter rank, and everything else is counted by each player's own client and shared over addon messages.
--
-- Award names and flavor text are original to HogTron. The end-of-run awards idea comes from Podium (Dalorrian,
-- CurseForge, All Rights Reserved): patterns only, no code or text taken.
