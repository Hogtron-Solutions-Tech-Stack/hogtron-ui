--- Full image prompt for one award (used by dev/gen_award_icons.py; kept here so the prompt lives with the award).
function A.IconPrompt(a)
  return (A.PROMPT_TEMPLATE:gsub("{subject}", a.icon or a.name))
end

--- True when award a can be given in context ctx ("dungeon" | "raid" | "bg").
function A.Eligible(a, ctx)
  if a.ctx == "any" then return true end
  for _, c in ipairs(a.ctx or {}) do if c == ctx then return true end end
  return false
end
